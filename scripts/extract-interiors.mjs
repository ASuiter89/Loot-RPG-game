// Pull seamless interior FLOOR and WALL field tiles out of the CC-BY-SA "[LPC]
// Floors" and "[LPC] Walls" packs (bluecarrot16 et al.) into a tiny atlas the game
// embeds, so built interiors get real wood / stone / marble / brick / adobe
// materials instead of borrowing the outdoor ground terrains. One representative
// field tile per style. See docs/asset-credits.md for the required attribution.
import { chromium } from 'playwright';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const floorsPng = join(root, 'scratch-shots/packs/interiors/floors_pack/lpc-floors/floors.png');
const wallsPng = join(root, 'scratch-shots/packs/interiors/walls_pack/lpc-walls/walls.png');
// floorStyle -> tile id in floors.png (32 cols); wallStyle -> tile id in walls.png (64 cols)
const FLOORS = { plank: 1216, carpet: 1440, stone: 1900, marble: 1904, tile: 2004, cobble: 1888 };
const WALLS = { log: 340, block: 380, brick: 364, panel: 984, smooth: 1012, cobble: 996 };

const exe = ['/opt/pw-browsers/chromium'].find((c) => existsSync(c));
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disable-gpu'], executablePath: exe });
const page = await browser.newPage();
const floorsB64 = readFileSync(floorsPng).toString('base64');
const wallsB64 = readFileSync(wallsPng).toString('base64');
const out = await page.evaluate(async ({ floorsB64, wallsB64, FLOORS, WALLS }) => {
  const load = async (b64) => { const im = new Image(); im.src = 'data:image/png;base64,' + b64; await im.decode(); return im; };
  const fim = await load(floorsB64), wim = await load(wallsB64);
  const A = 32;
  const fnames = Object.keys(FLOORS), wnames = Object.keys(WALLS);
  const cols = Math.max(fnames.length, wnames.length);
  const cv = document.createElement('canvas'); cv.width = cols * A; cv.height = 2 * A;
  const g = cv.getContext('2d'); g.imageSmoothingEnabled = false;
  const floors = {}, walls = {};
  fnames.forEach((nm, i) => { const id = FLOORS[nm]; g.drawImage(fim, (id % 32) * A, ((id / 32) | 0) * A, A, A, i * A, 0, A, A); floors[nm] = { dx: i * A, dy: 0 }; });
  wnames.forEach((nm, i) => { const id = WALLS[nm]; g.drawImage(wim, (id % 64) * A, ((id / 64) | 0) * A, A, A, i * A, A, A, A); walls[nm] = { dx: i * A, dy: A }; });
  return { atlas: cv.toDataURL('image/png'), floors, walls };
}, { floorsB64, wallsB64, FLOORS, WALLS });

const header = '// Interior atlas — seamless FLOOR and WALL field tiles (wood / stone / marble /\n'
  + '// brick / adobe / cobble) from the CC-BY-SA "[LPC] Floors" and "[LPC] Walls"\n'
  + '// packs (bluecarrot16, Lanea Zimmerman, et al.). Generated by\n'
  + '// scripts/extract-interiors.mjs. Entries are 32x32 tiles in INTERIORS_ATLAS keyed\n'
  + '// by interior floorStyle / wallStyle. See docs/asset-credits.md for attribution.\n';
writeFileSync(join(root, 'src/assets/interiorsAtlas.js'),
  header + 'export const INTERIORS_FLOORS = ' + JSON.stringify(out.floors) + ';\n'
  + 'export const INTERIORS_WALLS = ' + JSON.stringify(out.walls) + ';\n'
  + 'export const INTERIORS_ATLAS = ' + JSON.stringify(out.atlas) + ';\n');
console.log('wrote src/assets/interiorsAtlas.js (' + Object.keys(out.floors).length + ' floors, ' + Object.keys(out.walls).length + ' walls)');
await browser.close();
